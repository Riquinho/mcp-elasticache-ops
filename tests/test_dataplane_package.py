MAX_MODULE_LINES = 1300


@pytest.mark.parametrize("name", PUBLIC_NAMES)
def test_public_name_is_exported(name):
    assert hasattr(dataplane, name)


@pytest.mark.parametrize("name", PRIVATE_NAMES)
def test_private_name_is_exported(name):
    assert hasattr(dataplane, name)


def test_no_source_module_is_oversized():
    root = Path(dataplane.__file__).resolve().parents[1]
    sizes = {
        p.relative_to(root).as_posix(): len(p.read_text(encoding="utf-8").splitlines()) for p in root.rglob("*.py")
    }
    too_big = {p: n for p, n in sizes.items() if n > MAX_MODULE_LINES}
    assert not too_big, too_big


def test_submodules_are_packaged_together():
    pkg = Path(dataplane.__file__).parent
    modules = {p.stem for p in pkg.glob("*.py")}
    assert {"_core", "keyspace", "triage_report", "doctor", "fanout"} <= modules
