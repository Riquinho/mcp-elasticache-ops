"""Pin the public surface: sorted tool names and each tool's IAM action set.

Names are pinned against ``tests/tool_schemas.json`` and the IAM action sets against ``tests/iam_actions.json``;
both are regenerated by ``scripts/regen.py``. A tool or an IAM action that appears or disappears therefore shows
up as a reviewed diff, never silently. The README tool count must also equal the registry size.
"""

from __future__ import annotations

import json
import os
import re
from pathlib import Path

from fastmcp import Client

from mcp_elasticache_ops import server
from tests.test_iam_policy import _collect, audit  # noqa: F401  (audit is a fixture)

HERE = Path(__file__).parent
ROOT = HERE.parent
SCHEMAS = HERE / "tool_schemas.json"
IAM_PIN = HERE / "iam_actions.json"


async def _registry() -> list[str]:
    async with Client(server.mcp) as c:
        return sorted(t.name for t in await c.list_tools())


async def iam_actions(audit_ns) -> dict[str, list[str]]:  # noqa: ANN001
    per_tool, registered = await _collect(audit_ns)
    return {t: sorted(per_tool.get(t, set())) for t in sorted(registered) if per_tool.get(t)}


async def test_sorted_tool_names_match_the_pinned_schemas():
    pinned = sorted(json.loads(SCHEMAS.read_text(encoding="utf-8")))
    current = await _registry()
    assert current == pinned, (
        f"added {sorted(set(current) - set(pinned))}, removed {sorted(set(pinned) - set(current))}"
    )


async def test_each_tools_iam_action_set_matches_the_pin(audit):  # noqa: F811
    current = await iam_actions(audit)
    if os.environ.get("UPDATE_IAM_PIN"):
        IAM_PIN.write_text(json.dumps(current, indent=1, sort_keys=True) + "\n", encoding="utf-8", newline="\n")
    pinned = json.loads(IAM_PIN.read_text(encoding="utf-8"))
    drift = {
        t: {"pinned": pinned.get(t), "now": current.get(t)}
        for t in sorted(set(pinned) | set(current))
        if pinned.get(t) != current.get(t)
    }
    assert not drift, f"IAM action sets changed (run scripts/regen.py if intended): {drift}"


async def test_every_aws_tool_has_a_pinned_nonempty_action_set():
    pinned = json.loads(IAM_PIN.read_text(encoding="utf-8"))
    for name in (n for n in await _registry() if n.startswith("aws_")):
        assert pinned.get(name), f"{name} has no pinned IAM actions"
    for name, actions in pinned.items():
        assert all(
            re.fullmatch(r"(elasticache:(?:Describe|List)\w+|cloudwatch:(DescribeAlarms|GetMetricData))", a)
            for a in actions
        ), name


async def test_readme_and_changelog_tool_counts_match_the_registry():
    count = len(await _registry())
    readme = (ROOT / "README.md").read_text(encoding="utf-8")
    table_rows = len(re.findall(r"^\| `(?:aws|node|memcached)_[a-z_]+`", readme, flags=re.MULTILINE))
    assert table_rows == count, f"README table lists {table_rows} tools, registry has {count}"
    newest = (ROOT / "CHANGELOG.md").read_text(encoding="utf-8").split("\n## ", 2)[1]
    claimed = re.findall(r"\b(\d+) tools\b", newest)
    assert all(int(n) == count for n in claimed[:1]), f"newest CHANGELOG entry says {claimed}, registry has {count}"


async def test_tool_schema_snapshot_and_iam_matrix_cover_every_registered_tool():
    names = set(await _registry())
    snapshot = json.loads((ROOT / "tests" / "tool_schemas.json").read_text(encoding="utf-8"))
    assert set(snapshot) == names
    matrix = (ROOT / "docs" / "iam-matrix.md").read_text(encoding="utf-8")
    for name in (n for n in names if n.startswith("aws_")):
        assert f"`{name}`" in matrix, f"{name} missing from docs/iam-matrix.md"
